#!/usr/bin/env python3
"""Encode an approved 256x128 atlas's button slots for the native renderer.
Only button rectangles are emitted. The Sly logos and unused atlas pixels
are never included; those continue to come from the player's game data.
The generated include is checked in, so ordinary builds do not need Pillow
or a locally dumped game texture.
"""
from pathlib import Path
import argparse
from PIL import Image
ROOT=Path(__file__).resolve().parent
RECTS=[(1,1,32),(34,1,32),(67,1,32),(100,1,32),(133,1,32),(166,1,32),
       (1,34,36),(38,34,36),(75,34,36),(112,34,36),(149,34,13),(163,34,13),
       (177,34,12),(190,34,12),(203,34,32),(1,67,112),(114,67,96)]
def encode(source,output):
    image=Image.open(source).convert('RGBA')
    if image.size!=(256,128):raise ValueError('Button artwork must be exactly 256x128; it will not be resized')
    pixels=[];rectangles=[]
    for x,y,width in RECTS:
        rectangles.append((x,y,width,len(pixels)))
        for py in range(y,y+32):
            for px in range(x,x+width):
                r,g,b,a=image.getpixel((px,py))
                pixels.append((r>>4)<<12|(g>>4)<<8|(b>>4)<<4|(a>>4))
    text='// Generated by prepare_button_icons.py from the approved New 3DS artwork.\n'
    text+='// Only replacement controller glyphs; no original game logos or fonts.\n'
    text+='static constexpr struct {unsigned x,y,width,offset;} caneNewButtonRects[]={\n'
    text+=''.join('    {%d,%d,%d,%d},\n'%r for r in rectangles)+'};\n'
    text+='static constexpr uint16_t caneNewButtonPixels[]={\n'
    text+=''.join('    '+','.join(hex(v) for v in pixels[i:i+24])+',\n' for i in range(0,len(pixels),24))+'};\n'
    output.write_text(text)
    print('Encoded',len(pixels)*2,'bytes of button glyphs:',output)
if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source',type=Path)
    parser.add_argument('--output',type=Path,default=ROOT/'assets/buttons-new-3ds.inc')
    args=parser.parse_args();encode(args.source,args.output)
